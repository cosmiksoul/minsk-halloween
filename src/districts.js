// переводим в метры относительно центра карты
export function projectHotspots(center) {
  const [lat0, lon0] = center; const kx = Math.cos(lat0 * Math.PI / 180) * 111320, kz = 110574;
  return HOTSPOTS.map(h => ({ ...h, x: (h.lon - lon0) * kx, z: -(h.lat - lat0) * kz }));
}
